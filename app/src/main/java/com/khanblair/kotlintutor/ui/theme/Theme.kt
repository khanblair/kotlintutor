private val LocalIsDarkTheme = compositionLocalOf { false }

/** The color for "completed" / "correct" indicators — outside the Material role system on purpose. */
val successColor: Color
    @Composable get() = if (LocalIsDarkTheme.current) SuccessDark else SuccessLight

enum class ThemeMode { SYSTEM, LIGHT, DARK }

@Composable
fun KotlinTutorTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    content: @Composable () -> Unit,
) {
    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }
    val colorScheme = if (darkTheme) DarkColors else LightColors
    CompositionLocalProvider(LocalIsDarkTheme provides darkTheme) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content,
        )
    }
}
